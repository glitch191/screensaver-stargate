    static readonly int[] Lookup = BuildLookup();

    static int[] BuildLookup()
    {
        var map = new int[128];
        for (int i = 0; i < Glyphs.Length; i++)
            map[Glyphs[i].Char] = i;
        return map;
    }

    /// <summary>Glyph index for a character; lower case maps to upper case, unknown maps to space.</summary>
    public static int IndexOf(char c)
    {
        if (c >= 'a' && c <= 'z') c = (char)(c - 32);
        return c < 128 ? Lookup[c] : 0;
    }

    /// <summary>Returns an 8-bit image, one glyph after another horizontally, top row first.</summary>
    public static byte[] BuildAtlas(out int width, out int height)
    {
        width = Glyphs.Length * GlyphWidth;
        height = GlyphHeight;
        var pixels = new byte[width * height];
        for (int g = 0; g < Glyphs.Length; g++)
            for (int y = 0; y < GlyphHeight; y++)
                for (int x = 0; x < GlyphWidth; x++)
                    if (Glyphs[g].Rows[y][x] == '#')
                        pixels[y * width + g * GlyphWidth + x] = 255;
        return pixels;
    }
}
